import { test } from 'node:test'
import assert from 'node:assert/strict'
import { needsFullText } from './fullText.ts'

// 例に具体的な番号・中身の語を置かない（persona.test.ts と同じ決まり。規則が例の語に寄らないように）

test('needsFullText: 「決めてほしいこと」の類が見出し・太字・項目名にあれば当たる（#638）', () => {
  for (const t of [
    '調べました。\n\n## 決めてほしいこと\n\n1. 甲にするか乙にするか\n2. 既定を入にするか',
    '案は 2 つです。\n\n**決めること（2 つ）**\n- 甲\n- 乙\n\n決まれば進めます。',
    '下書きを置きました。\n\n確認したいこと:\n- 甲の扱い\n- 乙の扱い\n\n以上です。',
  ]) {
    assert.equal(needsFullText(t), true, t)
  }
})

test('needsFullText: 最後の段落に問いかけがあれば当たる。番号つきで並べた問い・あとに一言続く形も（#638）', () => {
  for (const t of [
    '甲と乙の 2 案があります。\n\nどちらにしますか？',
    '直しました。\n\nこのまま進めてよいですか。',
    '案を 3 つ出しました。\n\nどれにしますか？ 混ぜることもできます。',
    '聞きたいのは 2 点です。\n\n1. 甲はいま使っていますか。使っていなければ外します。\n2. 乙は要りますか。',
    '整理しました。\n\n**甲で進めてよいでしょうか**',
  ]) {
    assert.equal(needsFullText(t), true, t)
  }
})

test('needsFullText: 完了報告・途中の問い・引用やコードや表の中の「?」は当てない（狭い方に倒す。#638）', () => {
  for (const t of [
    '',
    '   ',
    '直して push しました。テストは通っています。',
    'マージしました。ブランチも消してあります。',
    // 途中に問いがあっても、最後の段落が報告なら当てない
    'なぜ落ちたのか？ 原因は設定の読み違いでした。\n\n直して、テストを足しました。',
    // 引用の中
    '頼まれた文はこうでした。\n\n> どちらにしますか？',
    // コードの中
    '正規表現を直しました。\n\n```\nconst re = /a?b/\n```',
    '置き換えたのは `x ? y : z` の部分です',
    // 表の中
    '結果です。\n\n| 項目 | 値 |\n| --- | --- |\n| 入れますか？ | はい |',
    // URL の中の「?」・型の書き方
    '直して push しました。\n\n画面は http://127.0.0.1:8787/?days=7#/s/abc で見られます。',
    '型は name?: string のままにしました。',
    // 表・コードで終わる返答は、その前の段落を「最後の段落」にしない
    '原因は何だったのか？\n\n| 項目 | 値 |\n| --- | --- |\n| 甲 | 乙 |',
    '何を変えたか？\n\n```\nconst a = 1\n```',
    // もう残っていない・決まったと言っている見出し
    '整理しました。\n\n## 決めることは残っていません\n\n全部入れました。',
    // 語が文の途中に出てくるだけ
    '前に決めることになっていた点は、甲に決めて実装しました。',
  ]) {
    assert.equal(needsFullText(t), false, t)
  }
})
